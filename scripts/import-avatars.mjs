// Imports avatar artwork into the app.
//
//   node scripts/import-avatars.mjs <source>
//
// <source> contains bodies/, faces/ and hats/. Each holds one folder per part, which holds one
// folder per view (front, frontright, right, top, topright), which holds mask.png and outline.png.
// Names are normalised to lowercase; any other file (stray layers etc.) is skipped.
// Output: public/avatars/<kind>/<part>/<view>/{mask,outline}.png and src/avatar/parts.generated.ts.
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = process.argv[2] ? resolve(process.argv[2]) : null;
if (!source || !existsSync(source)) {
  console.error("Usage: node scripts/import-avatars.mjs <folder containing bodies, faces and hats>");
  process.exit(1);
}

const KINDS = ["bodies", "faces", "hats"];
const VIEWS = ["front", "frontright", "right", "topright", "top"];

// Display names for folders whose name is several words run together.
const LABELS = {
  "1chef": "Chef", nohat: "No hat", fancychef: "Fancy chef", handkerchef: "Handkerchef", gnomehat: "Gnome hat",
  policehat: "Police hat", partyhat: "Party hat", tophat: "Top hat", knighthelmet: "Knight helmet", paperboat: "Paper boat",
  teddyfur: "Teddy fur", turtleshell: "Turtle shell", businesscasual: "Business casual"
};

const slug = name => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const label = name => LABELS[slug(name)] ?? name.charAt(0).toUpperCase() + name.slice(1).toLowerCase();
const dirs = path => readdirSync(path).filter(name => statSync(join(path, name)).isDirectory());
const findFile = (path, wanted) => readdirSync(path).find(name => name.toLowerCase() === wanted);

const target = join(root, "public", "avatars");
rmSync(target, { recursive: true, force: true });

const parts = {};
let copied = 0;
for (const kind of KINDS) {
  const kindDir = join(source, kind);
  parts[kind] = [];
  for (const name of dirs(kindDir).sort((a, b) => a.localeCompare(b, "en", { sensitivity: "base" }))) {
    const partDir = join(kindDir, name);
    const views = new Map(dirs(partDir).map(view => [view.toLowerCase(), view]));
    const missing = VIEWS.filter(view => !views.has(view));
    if (missing.length) {
      console.warn(`Skipping ${kind}/${name}: missing views ${missing.join(", ")}`);
      continue;
    }
    let complete = true;
    const files = [];
    for (const view of VIEWS) {
      const viewDir = join(partDir, views.get(view));
      const mask = findFile(viewDir, "mask.png");
      const outline = findFile(viewDir, "outline.png");
      if (!mask || !outline) { complete = false; break; }
      files.push([join(viewDir, mask), view, "mask.png"], [join(viewDir, outline), view, "outline.png"]);
    }
    if (!complete) {
      console.warn(`Skipping ${kind}/${name}: a view is missing its mask or outline`);
      continue;
    }
    for (const [from, view, file] of files) {
      const to = join(target, kind, slug(name), view, file);
      mkdirSync(dirname(to), { recursive: true });
      copyFileSync(from, to);
      copied++;
    }
    parts[kind].push({ id: slug(name), label: label(name) });
  }
}

const body = `// Generated by scripts/import-avatars.mjs. Do not edit by hand.
export interface PartInfo {
  id: string;
  label: string;
}

export const PARTS: { bodies: PartInfo[]; faces: PartInfo[]; hats: PartInfo[] } = ${JSON.stringify(parts, null, 2)};
`;
mkdirSync(join(root, "src", "avatar"), { recursive: true });
writeFileSync(join(root, "src", "avatar", "parts.generated.ts"), body);
console.log(`Imported ${parts.bodies.length} bodies, ${parts.faces.length} faces, ${parts.hats.length} hats (${copied} files).`);
